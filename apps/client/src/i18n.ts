const dicts: Record<Lang, Record<Key, string>> = { de, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang): T {
  return (key, vars = {}) =>
    dicts[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function useT(): T {
  const lang = useApp().ui.lang;
  return useMemo(() => translate(lang), [lang]);
}
